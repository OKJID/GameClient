void AfxRegisterStandardResources()
{
	Win32Resources& resources = Win32Resources::instance();
	resources.registerIds(kStandardSymbols, sizeof(kStandardSymbols) / sizeof(kStandardSymbols[0]));
	for (const AfxStandardString& entry : kStandardStrings)
	{
		resources.registerString(entry.id, entry.text);
	}
}
