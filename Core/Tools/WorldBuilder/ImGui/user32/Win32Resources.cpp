Win32Resources& Win32Resources::instance()
{
	static Win32Resources resources;
	return resources;
}

void Win32Resources::registerIds(const Win32NamedValue* values, size_t count)
{
	for (size_t index = 0; index < count; ++index)
	{
		m_ids[values[index].name] = values[index].value;
	}
}

void Win32Resources::registerString(UINT id, const char* text)
{
	m_strings[id] = text;
}

bool Win32Resources::load(const std::string& directory)
{
	m_directory = directory;
	registerIds(kStyleNames, sizeof(kStyleNames) / sizeof(kStyleNames[0]));
	registerIds(kVirtualKeyNames, sizeof(kVirtualKeyNames) / sizeof(kVirtualKeyNames[0]));

	std::string header;
	std::string script;
	if (!readFile(filePath("resource.h"), header) || !readFile(filePath("WorldBuilder.rc"), script))
	{
		return false;
	}

	parseDefines(header, m_ids);
	Win32ResourceParser(*this, Win32TokenizeResourceScript(script)).parse();
	return true;
}

bool Win32Resources::resolveName(LPCSTR name, UINT& id) const
{
	if (name == nullptr)
	{
		return false;
	}
	if (IS_INTRESOURCE(name))
	{
		id = static_cast<UINT>(reinterpret_cast<uintptr_t>(name));
		return true;
	}
	if (name[0] == '#')
	{
		id = static_cast<UINT>(std::strtoul(name + 1, nullptr, 10));
		return true;
	}
	return findId(name, id);
}

bool Win32Resources::findId(const std::string& name, UINT& id) const
{
	const auto it = m_ids.find(name);
	if (it == m_ids.end())
	{
		return false;
	}
	id = it->second;
	return true;
}

const char* Win32Resources::string(UINT id) const
{
	const std::string* text = findValue(m_strings, id);
	return text == nullptr ? nullptr : text->c_str();
}

