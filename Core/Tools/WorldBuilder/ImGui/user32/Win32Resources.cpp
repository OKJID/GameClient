bool readFile(const std::string& path, std::string& contents)
{
	std::ifstream file(Win32NativePath(path), std::ios::binary);
	if (!file)
	{
		return false;
	}
	std::ostringstream stream;
	stream << file.rdbuf();
	contents = stream.str();
	return true;
}

void parseDefines(const std::string& contents, std::map<std::string, UINT>& ids)
{
	for (const std::string& line : Win32SplitLines(contents))
	{
		std::istringstream stream(line);
		std::string keyword;
		std::string name;
		std::string value;
		stream >> keyword >> name >> value;
		if (keyword != "#define" || value.empty() || !(std::isdigit(static_cast<unsigned char>(value[0])) || value[0] == '-'))
		{
			continue;
		}
		ids[name] = static_cast<UINT>(std::strtol(value.c_str(), nullptr, 0));
	}
}

template<class Value>
const Value* findValue(const std::map<UINT, Value>& values, UINT id)
{
	const auto it = values.find(id);
	return it == values.end() ? nullptr : &it->second;
}

