int LoadStringA(HINSTANCE, UINT id, LPSTR buffer, int bufferMax)
{
	const char* text = Win32Resources::instance().string(id);
	if (text == nullptr || buffer == nullptr || bufferMax < 0)
	{
		return 0;
	}
	if (bufferMax == 0)
	{
		*reinterpret_cast<const char**>(buffer) = text;
		return static_cast<int>(strlen(text));
	}
	return Win32CopyWindowText(text, buffer, bufferMax);
}
